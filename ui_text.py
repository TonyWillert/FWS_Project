def local_upload_error(language: str, message: str) -> str:
    """Übersetzt bekannte CSV-/Modellmeldungen für den englischen Modus."""
    if language == "de":
        return message
    prefixes = {
        "Die CSV konnte nicht gelesen werden: ": "Could not read the CSV: ",
        "Diese Spalten fehlen: ": "Missing required columns: ",
        "Leere Kurskennung in ": "Empty course identifier in ",
        "Für diese Stichtage gibt es kein Modell: ": "No model for these course days: ",
        "Für diese Module gibt es keine Trainingsdaten: ": "No training data for these modules: ",
    }
    full = {
        "Die CSV enthält keine Kurseinträge.": "The CSV contains no course entries.",
        "Benötigte Spalten enthalten leere Werte.": "Required columns contain empty values.",
        "Stichtag, Anmeldung, Klicks und Assessments müssen Zahlen sein.":
            "Course day, registration, clicks and assessments must be numbers.",
        "Stichtage müssen ganze Kurstage sein.": "Course days must be whole numbers.",
        "Ein Kurseintrag wurde erst nach seinem Stichtag angemeldet.":
            "A course entry was registered after its course day.",
        "Klicks und Assessmentzahlen dürfen nicht negativ sein.":
            "Click and assessment counts must not be negative.",
        "Klicks und Assessmentzahlen müssen ganze Zahlen sein.":
            "Click and assessment counts must be whole numbers.",
        "Fehlende Assessments übersteigen die fälligen Assessments.":
            "Missing assessments exceed due assessments.",
        "Klicks der letzten Woche übersteigen die gesamten Klicks.":
            "Last-week clicks exceed total clicks.",
        "Ein Kurseintrag steht am selben Stichtag mehrfach in der CSV.":
            "A course entry appears more than once for the same day.",
    }
    if message in full:
        return full[message]
    if message.startswith("Das Modell für Tag "):
        value = message.removeprefix("Das Modell für Tag ")
        if " fehlt: " in value:
            day, file = value.split(" fehlt: ", 1)
            return f"Missing model for day {day}: {file}"
        if value.endswith(" hat keine positive Klasse 1."):
            day = value.removesuffix(" hat keine positive Klasse 1.")
            return f"The model for day {day} has no positive class 1."
        if value.endswith(" lieferte ungültige Werte."):
            day = value.removesuffix(" lieferte ungültige Werte.")
            return f"The model for day {day} returned invalid values."
    for source, target in prefixes.items():
        if message.startswith(source):
            return target + message.removeprefix(source)
    return tr(language, "upload_error")
