def tr(language: str, key: str, **values) -> str:
    """Liest einen Oberflächentext und setzt optionale Zahlen und Namen ein."""
    return TEXT[language][key].format(**values)


def local_group(language: str, value: str) -> str:
    """Übersetzt die internen Prüfgruppen nur für die Anzeige."""
